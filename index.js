let currentLanguage = "de";
const languageToggle = document.querySelector("[data-lang-toggle]");
const languageFlag = document.querySelector("[data-lang-flag]");
const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector(".nav-links");
const statusDialog = document.querySelector("[data-status-dialog]");

function translate(language) {
	currentLanguage = language;
	document.documentElement.lang = language;

	document.querySelectorAll("[data-i18n]").forEach((element) => {
		const key = element.dataset.i18n;
		if (translations[language][key])
			element.textContent = translations[language][key];
	});

	if (languageFlag) {
		languageFlag.src =
			language === "de"
				? "src/icons/icons8-england-48.png"
				: "src/icons/icons8-germany-48.png";
		languageFlag.alt = language === "de" ? "English" : "Deutsch";
	}
}

languageToggle?.addEventListener("click", () => {
	translate(currentLanguage === "de" ? "en" : "de");
});

menuToggle?.addEventListener("click", () => {
	const isOpen = navLinks.classList.toggle("open");
	menuToggle.setAttribute("aria-expanded", String(isOpen));
});

document.querySelectorAll(".nav-links a").forEach((link) => {
	link.addEventListener("click", () => {
		navLinks.classList.remove("open");
		menuToggle?.setAttribute("aria-expanded", "false");
	});
});

document.querySelectorAll("[data-open-status]").forEach((button) => {
	button.addEventListener("click", () => {
		navLinks.classList.remove("open");
		menuToggle?.setAttribute("aria-expanded", "false");
		if (typeof statusDialog.showModal === "function") {
			statusDialog.showModal();
		} else {
			statusDialog.setAttribute("open", "");
		}
	});
});

document
	.querySelector("[data-close-status]")
	?.addEventListener("click", () => statusDialog.close());
statusDialog?.addEventListener("click", (event) => {
	const rect = statusDialog.getBoundingClientRect();
	const clickedBackdrop =
		event.clientX < rect.left ||
		event.clientX > rect.right ||
		event.clientY < rect.top ||
		event.clientY > rect.bottom;
	if (clickedBackdrop) statusDialog.close();
});

const sections = [...document.querySelectorAll("main section[id]")];
const navAnchors = [...document.querySelectorAll(".nav-links a[href^='#']")];
const navObserver = new IntersectionObserver(
	(entries) => {
		entries.forEach((entry) => {
			if (!entry.isIntersecting) return;
			navAnchors.forEach((anchor) =>
				anchor.classList.toggle(
					"active",
					anchor.getAttribute("href") === `#${entry.target.id}`,
				),
			);
		});
	},
	{ rootMargin: "-45% 0px -50% 0px", threshold: 0 },
);
sections.forEach((section) => navObserver.observe(section));

const revealObserver = new IntersectionObserver(
	(entries) => {
		entries.forEach((entry) => {
			if (entry.isIntersecting) {
				entry.target.classList.add("visible");
				revealObserver.unobserve(entry.target);
			}
		});
	},
	{ threshold: 0.12 },
);
document
	.querySelectorAll(".reveal")
	.forEach((element) => revealObserver.observe(element));

document.querySelector("[data-year]").textContent = new Date().getFullYear();
translate("de");

